import {buildSchemaDDL, resolveTables, DEFAULT_TABLE_PREFIX} from '../src/postgresSchema.ts';

/**
 * Print the Postgres registry-state DDL for a given table prefix. The DDL is
 * derived from the same source of truth the runtime uses (postgresSchema.ts), so
 * db/schema.sql never drifts from what autoCreateSchema would produce.
 *
 * Usage: pnpm schema:print [-- --prefix=verdaccio_] > db/schema.sql
 */
const arg = process.argv.find((a) => a.startsWith('--prefix='));
const tablePrefix = arg ? arg.slice('--prefix='.length) : DEFAULT_TABLE_PREFIX;

// resolveTables validates the prefix (throws on an invalid one) before it is used.
const tables = resolveTables({postgres: {tablePrefix}} as never);

const prefixLabel = tablePrefix === '' ? 'none (bare table names)' : `'${tablePrefix}'`;
const regenerate =
  tablePrefix === ''
    ? 'pnpm schema:print > db/schema.sql'
    : `pnpm schema:print -- --prefix=${tablePrefix} > db/schema.sql`;

const header =
  `-- Generated by scripts/print-schema.ts (tablePrefix: ${prefixLabel}). Do not edit by hand.\n` +
  `-- Regenerate: ${regenerate}\n` +
  '--\n' +
  '-- Pre-provision these tables for a DML-only runtime role and set\n' +
  '-- `postgres.autoCreateSchema: false` in the plugin config. On PostgreSQL 15+ a\n' +
  '-- role would otherwise still need CREATE on the schema even for the no-op\n' +
  '-- CREATE TABLE IF NOT EXISTS that autoCreateSchema runs.\n';

process.stdout.write(`${header}\n${buildSchemaDDL(tables)}\n`);
